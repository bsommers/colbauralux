#!/usr/bin/env node
// Generate docs/BUILD-TIMELINE.md (Mermaid gantt + stage table) from the tracker snapshot in docs/swarm/tracker/.
// Usage: node tools/build-timeline.mjs [--refresh]   (--refresh first copies .tracker/ into docs/swarm/tracker/)
import { readFileSync, readdirSync, writeFileSync, cpSync, existsSync } from 'node:fs';
const SNAP = 'docs/swarm/tracker';
if (process.argv.includes('--refresh') && existsSync('.tracker')) { cpSync('.tracker/events', `${SNAP}/events`, { recursive: true }); cpSync('.tracker/plan.json', `${SNAP}/plan.json`); }
const plan = JSON.parse(readFileSync(`${SNAP}/plan.json`, 'utf8'));
const rows = [];
for (const f of readdirSync(`${SNAP}/events`).filter((n) => n.endsWith('.jsonl'))) {
  const ev = readFileSync(`${SNAP}/events/${f}`, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
  const start = ev.find((e) => e.state === 'start') ?? ev[0], done = [...ev].reverse().find((e) => e.state === 'done') ?? ev.at(-1);
  const id = f.replace('.jsonl', ''), a = plan.agents.find((x) => x.id === id) ?? {};
  rows.push({ id, name: a.name ?? id, phase: a.phase ?? '?', model: a.model ?? '?', t0: Date.parse(start.t), t1: Date.parse(done.t), msg: done.msg ?? '', events: ev.length });
}
rows.sort((a, b) => a.t0 - b.t0);
const T0 = Math.min(...rows.map((r) => r.t0)), T1 = Math.max(...rows.map((r) => r.t1));
const fmt = (ms) => { const s = Math.round(ms / 1000); return s >= 60 ? `${Math.floor(s / 60)}m ${String(s % 60).padStart(2, '0')}s` : `${s}s`; };
const hms = (ms) => new Date(ms).toISOString().slice(11, 19);
const sum = rows.reduce((n, r) => n + (r.t1 - r.t0), 0);
const phases = [...new Set(rows.map((r) => r.phase))].sort();
let g = `gantt\n    title Colbauralux swarm build (UTC, ${new Date(T0).toISOString().slice(0, 10)})\n    dateFormat HH:mm:ss\n    axisFormat %H:%M\n`;
for (const p of phases) {
  g += `    section ${p}\n`;
  for (const r of rows.filter((x) => x.phase === p)) g += `    ${r.name.replace(/[:;#]/g, ' ')} :${r.t1 - r.t0 < 90000 ? 'active, ' : ''}${r.id.replace(/-/g, '_')}, ${hms(r.t0)}, ${hms(Math.max(r.t1, r.t0 + 1000))}\n`;
}
const md = `# Build timeline

[README](../README.md) · generated by \`node tools/build-timeline.mjs\` from the tracker snapshot in [\`docs/swarm/tracker/\`](swarm/tracker/) (the live dashboard data: \`npm run tracker\`).

**Wall-clock for the agent swarm: ${fmt(T1 - T0)}** (${hms(T0)} to ${hms(T1)} UTC). **${rows.length} agents**, ${fmt(sum)} of summed agent time (so about ${(sum / (T1 - T0)).toFixed(1)}x parallelism). All agents ran on the \`${[...new Set(rows.map((r) => r.model))].join(', ')}\` tier.

\`\`\`mermaid
${g}\`\`\`

## Stages

| Stage | Agent | Model | Start | End | Duration | Result |
|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.phase} | ${r.name} (\`${r.id}\`) | ${r.model} | ${hms(r.t0)} | ${hms(r.t1)} | ${fmt(r.t1 - r.t0)} | ${r.msg.replace(/\|/g, '/')} |`).join('\n')}

## What the tracker does not show

- Orchestrator work before the first agent started: scaffolding with game-factory, copying the Omega Ratrace reference art, writing \`ARCHITECTURE.md\`, \`defs.js\` and \`SWARM.md\`.
- Follow-up agents resumed outside the tracker: the balance retune (levels 2-14, per-AI difficulty override) and the cheese-wheel art polish. They are recorded in [BALANCE.md](BALANCE.md) and the agent reports under [swarm/reports/](swarm/reports/).
- Orchestrator integration work after the swarm: output-file rename, site links, final gates, commit and push.
`;
writeFileSync('docs/BUILD-TIMELINE.md', md);
if (existsSync('README.md')) {
  const rd = readFileSync('README.md', 'utf8'), A = '<!-- TIMELINE:BEGIN -->', B = '<!-- TIMELINE:END -->';
  if (rd.includes(A) && rd.includes(B)) {
    const blk = `${A}\nThe agent swarm built the game in **${fmt(T1 - T0)}** of wall-clock time (${rows.length} agents, ${(sum / (T1 - T0)).toFixed(1)}x parallelism). Stage table and details: [docs/BUILD-TIMELINE.md](docs/BUILD-TIMELINE.md).\n\n\`\`\`mermaid\n${g}\`\`\`\n${B}`;
    writeFileSync('README.md', rd.slice(0, rd.indexOf(A)) + blk + rd.slice(rd.indexOf(B) + B.length));
  }
}
console.log(`wrote docs/BUILD-TIMELINE.md: ${rows.length} agents, wall ${fmt(T1 - T0)}`);
